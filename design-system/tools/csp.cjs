#!/usr/bin/env node
// Writes a Content-Security-Policy <meta> into every public page.
//
// GitHub Pages cannot send security headers, so the policy lives in the page.
// Each page may only run its own scripts (inline scripts are allowed by their
// SHA-256 hash), may only fetch from its own site, and may not be embedded as
// a plugin or change its base URL. Jobwizard may also talk to api.github.com,
// because publishing goes through the GitHub API.
//
//   node design-system/tools/csp.cjs           update all pages
//   node design-system/tools/csp.cjs --check   fail if a page is missing or has an outdated policy
//
// Run it after changing an inline <script>, for example after bundle-header.cjs.
// Numbered application pages (0001, 0002 …) are skipped: they set <base> to
// extruda.dk and are generated by Jobwizard.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '../..');
const skip = new Set(['.git', '_site', 'node_modules', 'Assets', 'assets', 'css', 'js', 'tools', 'tests', 'installer', 'download']);
const extraConnect = { 'jobwizard/': ['https://api.github.com'] };

function findPages(dir = root) {
  const found = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (skip.has(entry.name) || entry.name.startsWith('.') || /^\d{4}$/.test(entry.name)) continue;
      found.push(...findPages(full));
    } else if (entry.name.endsWith('.html')) {
      found.push(full);
    }
  }
  return found.sort();
}

// Inline scripts that the browser executes (JSON data blocks are not executed).
function inlineScriptHashes(html) {
  const hashes = [];
  for (const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attributes = match[1];
    if (/\bsrc\s*=/.test(attributes)) continue;
    const type = (/\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attributes) || [])[1];
    if (type && !/^(text\/javascript|module|application\/javascript)$/i.test(type)) continue;
    hashes.push(`'sha256-${crypto.createHash('sha256').update(match[2], 'utf8').digest('base64')}'`);
  }
  return [...new Set(hashes)];
}

function policyFor(file, html) {
  const relative = path.relative(root, file).split(path.sep).join('/');
  const connect = ["'self'", ...Object.entries(extraConnect).filter(([prefix]) => relative.startsWith(prefix)).flatMap(([, hosts]) => hosts)];
  return [
    "default-src 'self'",
    `script-src 'self' ${inlineScriptHashes(html).join(' ')}`.trim(),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self' data:",
    "media-src 'self' blob:",
    `connect-src ${connect.join(' ')}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
  ].join('; ');
}

const metaPattern = /\n[ \t]*<meta http-equiv="Content-Security-Policy" content="[^"]*">/i;
function withPolicy(html, policy) {
  const tag = `<meta http-equiv="Content-Security-Policy" content="${policy}">`;
  const clean = html.replace(metaPattern, '');
  const charset = /([ \t]*)<meta charset=[^>]*>/i.exec(clean);
  if (!charset) throw new Error('no <meta charset> to place the policy after');
  const at = charset.index + charset[0].length;
  return clean.slice(0, at) + '\n' + charset[1] + tag + clean.slice(at);
}

const check = process.argv.includes('--check');
const outdated = [];
for (const file of findPages()) {
  const html = fs.readFileSync(file, 'utf8');
  // Hash the page without its own policy tag, so the result is stable.
  const policy = policyFor(file, html.replace(metaPattern, ''));
  const next = withPolicy(html, policy);
  if (next === html) continue;
  outdated.push(path.relative(root, file));
  if (!check) fs.writeFileSync(file, next);
}
if (check && outdated.length) {
  console.error('Content-Security-Policy missing or outdated. Run: node design-system/tools/csp.cjs\n  ' + outdated.join('\n  '));
  process.exit(1);
}
console.log(check ? 'CSP OK: every page has an up-to-date policy.' : `CSP written to ${outdated.length} page(s).`);
